class _FakePgPool:
    """
    Stateful Postgres catalog + SQLite-backed execution adapter for `PgClient._pool`.
    Parses the DDL in `MIGRATION_044_045_SQL` (tables, indexes, RLS, `pg_roles`-guarded
    policies) and executes the parameterized `INSERT ... RETURNING *` / `SELECT`
    statements generated by `PgClient.table(...)`.
    """

    def __init__(self, *, has_service_role: bool = False):
        self.has_service_role = has_service_role
        self.ddl_runs = 0
        self.columns: Dict[str, Dict[str, str]] = {}
        self.pkeys: Dict[str, List[str]] = {}
        self.fkeys: Dict[Any, Any] = {}
        self.funcs: Dict[str, Any] = {}

        self._tables: Dict[str, Dict[str, Any]] = {}
        self._indexes: Dict[str, List[str]] = {}
        self._policies: Dict[str, List[str]] = {}
        self._sqlite = sqlite3.connect(":memory:")
        self._sqlite.row_factory = sqlite3.Row

    def _ensure_sqlite_table(self, name: str, cols: Dict[str, str], pk: str) -> None:
        self._tables.setdefault(name, {"cols": cols, "pk": pk, "rls": False})
        self._indexes.setdefault(name, [f"{name}_pkey"])
        self._policies.setdefault(name, [])
        col_defs = ", ".join(f'"{c}" TEXT' for c in cols)
        self._sqlite.execute(f'CREATE TABLE IF NOT EXISTS "{name}" ({col_defs})')
        self._sqlite.commit()

    def table_columns(self, table: str) -> Dict[str, str]:
        if table not in self.columns:
            if table not in self._tables:
                raise RuntimeError(f'relation "public.{table}" does not exist')
            self.columns[table] = dict(self._tables[table]["cols"])
        return self.columns[table]

    def primary_key(self, table: str) -> List[str]:
        if table not in self.pkeys:
            if table not in self._tables:
                return []
            self.pkeys[table] = [self._tables[table]["pk"]]
        return self.pkeys[table]

    def _apply_ddl(self, sql: str) -> None:
        self.ddl_runs += 1
        if "CREATE TABLE IF NOT EXISTS public.flow_consent_audit_logs" in sql:
            self._ensure_sqlite_table(
                "flow_consent_audit_logs",
                {
                    "id": "uuid",
                    "user_id": "text",
                    "temp_id": "text",
                    "action": "text",
                    "created_at": "timestamp with time zone",
                },
                "id",
            )
        if "CREATE TABLE IF NOT EXISTS public.payment_webhook_events" in sql:
            self._ensure_sqlite_table(
                "payment_webhook_events",
                {
                    "id": "uuid",
                    "provider": "text",
                    "provider_event_id": "text",
                    "event_type": "text",
                    "user_id": "text",
                    "order_id": "text",
                    "current_tier": "text",
                    "target_tier": "text",
                    "amount": "bigint",
                    "status": "text",
                    "reason": "text",
                    "raw_payload": "jsonb",
                    "created_at": "timestamp with time zone",
                },
                "id",
            )

        for idx_match in re.finditer(
            r"CREATE INDEX IF NOT EXISTS\s+(\w+)\s+ON\s+public\.(\w+)",
            sql,
            re.IGNORECASE,
        ):
            idx_name, tbl_name = idx_match.group(1), idx_match.group(2)
            idxs = self._indexes.setdefault(tbl_name, [])
            if idx_name not in idxs:
                idxs.append(idx_name)

        for rls_match in re.finditer(
            r"ALTER TABLE\s+public\.(\w+)\s+ENABLE ROW LEVEL SECURITY",
            sql,
            re.IGNORECASE,
        ):
            tbl_name = rls_match.group(1)
            if tbl_name in self._tables:
                self._tables[tbl_name]["rls"] = True

        # 044 policy (no TO service_role required)
        if 'CREATE POLICY "flow_consent_audit_logs_own"' in sql:
            pols = self._policies.setdefault("flow_consent_audit_logs", [])
            if "flow_consent_audit_logs_own" not in pols:
                pols.append("flow_consent_audit_logs_own")

        # 045 policy: check whether SQL properly guards `TO service_role` with pg_roles check
        if 'CREATE POLICY "payment_webhook_events_service_role_only"' in sql:
            guarded = "FROM pg_roles WHERE rolname = 'service_role'" in sql
            if not self.has_service_role and not guarded:
                raise RuntimeError('role "service_role" does not exist')
            if self.has_service_role:
                pols = self._policies.setdefault("payment_webhook_events", [])
                if "payment_webhook_events_service_role_only" not in pols:
                    pols.append("payment_webhook_events_service_role_only")

    def run(self, sql: str, params: Sequence[Any] = (), fetch: bool = True) -> List[Dict[str, Any]]:
        s = sql.strip()

        if "CREATE TABLE IF NOT EXISTS" in s:
            self._apply_ddl(s)
            return []

        if "FROM pg_tables" in s:
            return [
                {"tablename": t, "rowsecurity": info["rls"]}
                for t, info in sorted(self._tables.items())
            ]

        if "FROM pg_indexes" in s:
            rows = []
            for t in sorted(self._indexes):
                for idx in sorted(self._indexes[t]):
                    rows.append({"tablename": t, "indexname": idx})
            return rows

        if "FROM pg_policies" in s:
            rows = []
            for t in sorted(self._policies):
                for pol in sorted(self._policies[t]):
                    rows.append({"tablename": t, "policyname": pol})
            return rows

        ins = re.match(
            r'^INSERT INTO public\."(\w+)" AS t \(([^)]+)\) VALUES \((.+)\) RETURNING \*$',
            s,
        )
        if ins:
            tbl = ins.group(1)
            col_names = [c.strip().strip('"') for c in ins.group(2).split(",")]
            schema_cols = self._tables[tbl]["cols"]
            row_dict: Dict[str, Any] = {}
            for col_name, raw_val in zip(col_names, params):
                # Unwrap psycopg2.extras.Json if present
                if hasattr(raw_val, "adapted"):
                    row_dict[col_name] = raw_val.adapted
                else:
                    row_dict[col_name] = raw_val

            # Fill server defaults identical to Postgres 044 / 045 DDL
            row_dict.setdefault("id", str(uuid.uuid4()))
            row_dict.setdefault("created_at", datetime.now(timezone.utc).isoformat())
            if tbl == "flow_consent_audit_logs":
                row_dict.setdefault("action", "process_confirm")
            elif tbl == "payment_webhook_events":
                row_dict.setdefault("status", "needs_manual_review")
                row_dict.setdefault("raw_payload", {})

            all_cols = list(schema_cols.keys())
            placeholders = ", ".join("?" for _ in all_cols)
            stored_vals = [
                json.dumps(row_dict.get(c)) if schema_cols[c] == "jsonb" and row_dict.get(c) is not None
                else (str(row_dict.get(c)) if row_dict.get(c) is not None else None)
                for c in all_cols
            ]
            col_sql = ", ".join(f'"{c}"' for c in all_cols)
            self._sqlite.execute(f'INSERT INTO "{tbl}" ({col_sql}) VALUES ({placeholders})', stored_vals)
            self._sqlite.commit()
            return [row_dict] if fetch else []

        sel = re.match(r'^SELECT .+ FROM public\."(\w+)" t', s)
        if sel:
            tbl = sel.group(1)
            schema_cols = self._tables[tbl]["cols"]
            cur = self._sqlite.execute(f'SELECT * FROM "{tbl}"')
            out = []
            for r in cur.fetchall():
                d: Dict[str, Any] = {}
                for c in schema_cols:
                    v = r[c]
                    if v is not None and schema_cols[c] == "jsonb":
                        v = json.loads(v)
                    elif v is not None and schema_cols[c] == "bigint":
                        v = int(v)
                    d[c] = v
                out.append(d)
            return out

        raise AssertionError(f"Unhandled SQL in _FakePgPool: {s[:120]}")


def _make_pg_client(*, has_service_role: bool = False) -> tuple[PgClient, _FakePgPool]:
    pool = _FakePgPool(has_service_role=has_service_role)
    pg = PgClient.__new__(PgClient)
    pg._pool = pool
    pg._supabase_factory = None
    pg._supabase = None
    return pg, pool


def test_ensure_twice_and_insert_via_pg_client_without_service_role():
    pg, pool = _make_pg_client(has_service_role=False)

    # Run ensure 2 consecutive times: idempotent, no error even without `service_role`
    res1 = M45.ensure_044_045_schema(force=True, db=pg)
    res2 = M45.ensure_044_045_schema(force=True, db=pg)
    assert res1["ok"] is True and res1["status"] == "ensured"
    assert res2["ok"] is True and res2["status"] == "ensured"
    assert pool.ddl_runs == 2

    # Insert into flow_consent_audit_logs (044) through real PgClient.table(...).insert(...)
    uid = str(uuid.uuid4())
    ins_044 = (
        pg.table("flow_consent_audit_logs")
        .insert({"user_id": uid, "temp_id": "abcdef0123456789", "action": "process_confirm"})
        .execute()
    )
    assert len(ins_044.data) == 1
    assert ins_044.data[0]["user_id"] == uid
    assert ins_044.data[0]["temp_id"] == "abcdef0123456789"
    assert ins_044.data[0]["id"]

    # Insert into payment_webhook_events (045) through real PgClient.table(...).insert(...)
    ins_045 = (
        pg.table("payment_webhook_events")
        .insert({
            "provider": "sepay",
            "provider_event_id": "sepay-999",
            "event_type": "transfer_in",
            "user_id": uid,
            "amount": 49000,
            "status": "needs_manual_review",
            "reason": "ambiguous_tier_amount",
            "raw_payload": {"order_code": "VG12345678"},
        })
        .execute()
    )
    assert len(ins_045.data) == 1
    assert ins_045.data[0]["provider"] == "sepay"
    assert ins_045.data[0]["amount"] == 49000
    assert ins_045.data[0]["raw_payload"] == {"order_code": "VG12345678"}

    # Select back via PgClient
    rows_044 = pg.table("flow_consent_audit_logs").select("*").execute().data
    rows_045 = pg.table("payment_webhook_events").select("*").execute().data
    assert len(rows_044) == 1 and rows_044[0]["user_id"] == uid
    assert len(rows_045) == 1 and rows_045[0]["amount"] == 49000

    # Read-only probe verifies both tables, index counts, and RLS
    probe = M45.probe_044_045_tables(db=pg)
    assert probe["ok"] is True and probe["all_ready"] is True
    assert probe["tables"]["flow_consent_audit_logs"]["exists"] is True
    assert probe["tables"]["flow_consent_audit_logs"]["rls_enabled"] is True
    assert probe["tables"]["flow_consent_audit_logs"]["index_count"] == 3
    assert probe["tables"]["payment_webhook_events"]["exists"] is True
    assert probe["tables"]["payment_webhook_events"]["rls_enabled"] is True
    assert probe["tables"]["payment_webhook_events"]["index_count"] == 4
    assert probe["tables"]["payment_webhook_events"]["policies"] == []


