def test_startup_redis_lock_prevents_overlap_and_supabase_skips(monkeypatch):
    rc = fakeredis.FakeRedis(decode_responses=True)
    pg, pool = _make_pg_client(has_service_role=False)

    # When DB_BACKEND=supabase -> skipped cleanly
    monkeypatch.setattr(database, "DB_BACKEND", "supabase")
    assert M45.ensure_044_045_once_on_startup(rc=rc)["status"] == "skipped_not_postgres"
    assert pool.ddl_runs == 0

    # When DB_BACKEND=postgres -> worker 1 runs DDL, worker 2 sees SET NX lock
    monkeypatch.setattr(database, "DB_BACKEND", "postgres")
    monkeypatch.setenv("DATABASE_URL", "postgresql://app:secretpw@vidgrab-backup:5432/vidgrab")
    monkeypatch.setattr(database, "get_service_client", lambda: pg)
    monkeypatch.setattr(M45, "_SCHEMA_044_045_ENSURED", False)

    w1 = M45.ensure_044_045_once_on_startup(rc=rc)
    w2 = M45.ensure_044_045_once_on_startup(rc=rc)
    assert w1["ok"] is True and w1["status"] == "ensured"
    assert w2["ok"] is True and w2["status"] == "skipped_locked"
    assert pool.ddl_runs == 1


def test_startup_failure_logs_alerts_telegram_scrubs_secret_and_never_crashes(monkeypatch):
    rc = fakeredis.FakeRedis(decode_responses=True)
    sent_messages: List[str] = []

    monkeypatch.setattr(database, "DB_BACKEND", "postgres")
    monkeypatch.setenv("DATABASE_URL", "postgresql://app:MyTopSecretPw99@vidgrab-backup:5432/vidgrab")

    class _BrokenPool:
        def run(self, *a, **kw):
            raise RuntimeError("FATAL connect postgresql://app:MyTopSecretPw99@vidgrab-backup:5432/vidgrab refused")

    class _BrokenDb:
        _pool = _BrokenPool()

    monkeypatch.setattr(database, "get_service_client", lambda: _BrokenDb())
    monkeypatch.setattr(
        "app.core.notifications.send_telegram_message_sync",
        lambda msg, parse_mode="HTML": sent_messages.append(msg) or True,
    )

    res = M45.ensure_044_045_once_on_startup(rc=rc)
    assert res["ok"] is False and res["status"] == "error"
    assert "MyTopSecretPw99" not in json.dumps(res)
    assert len(sent_messages) == 1
    assert "MyTopSecretPw99" not in sent_messages[0]
    # Lock was released on error so a retry can run
    assert rc.get(M45.STARTUP_LOCK_KEY) is None


def test_admin_tables_044_045_probe_endpoint(monkeypatch):
    from app.api.admin_db_migration import verify_admin
    from app.main import app as fastapi_app

    pg, _ = _make_pg_client(has_service_role=False)
    M45.ensure_044_045_schema(force=True, db=pg)

    monkeypatch.setattr(database, "DB_BACKEND", "postgres")
    monkeypatch.setenv("DATABASE_URL", "postgresql://app:HiddenPw123@vidgrab-backup:5432/vidgrab")
    monkeypatch.setattr(database, "get_service_client", lambda: pg)

    client = TestClient(fastapi_app, raise_server_exceptions=False)
    assert client.get("/api/v1/admin/db-migration/tables-044-045").status_code in (401, 403)

    fastapi_app.dependency_overrides[verify_admin] = lambda: None
    try:
        resp = client.get("/api/v1/admin/db-migration/tables-044-045")
        assert resp.status_code == 200
        assert "HiddenPw123" not in resp.text
        data = resp.json()
        assert data["ok"] is True and data["all_ready"] is True
        assert data["tables"]["flow_consent_audit_logs"]["exists"] is True
        assert data["tables"]["payment_webhook_events"]["exists"] is True
    finally:
        fastapi_app.dependency_overrides.pop(verify_admin, None)
